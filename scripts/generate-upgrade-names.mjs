// Generates src/lib/names/upgradeNames.generated.ts from the clash-of-clans-data package.
// Usage: npm run generate:names  (update the package first to pick up new game content)

import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as prettier from 'prettier'

const PACKAGE = 'clash-of-clans-data'
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
// Read from node_modules directly: the package's "exports" doesn't expose package.json.
const packageDir = join(root, 'node_modules', PACKAGE)
const dataDir = join(packageDir, 'data')
const { version } = JSON.parse(await readFile(join(packageDir, 'package.json'), 'utf8'))

const outFile = join(root, 'src/lib/names/upgradeNames.generated.ts')

/**
 * Each group is the set of data folders whose entries can appear in one kind of export section.
 * Folders are read non-recursively, so e.g. home/other/helpers is not included.
 * Left out on purpose: traps, guardians, hero equipment, helpers and crafted-defense modules,
 * none of which appear in the sections the parser tracks.
 */
const GROUPS = {
  'home-building': [
    'home/army-buildings',
    'home/defenses',
    'home/resource-buildings',
    'home/town-hall',
    'home/walls',
    'home/other',
  ],
  'home-hero': ['home/heroes'],
  'home-troop': ['home/troops'],
  'home-spell': ['home/spells'],
  'home-siege-machine': ['home/siege-machines'],
  'home-pet': ['home/pets'],
  'builder-building': [
    'builder/army-buildings',
    'builder/defenses',
    'builder/resource-buildings',
    'builder/builder-hall',
    'builder/walls',
    'builder/other',
  ],
  'builder-hero': ['builder/heroes'],
  'builder-troop': ['builder/troops'],
}

async function readGroup(folders) {
  const names = new Map()
  for (const folder of folders) {
    const entries = await readdir(join(dataDir, folder), { withFileTypes: true })
    for (const entry of entries) {
      if (!entry.isFile() || !entry.name.endsWith('.json')) continue
      const json = JSON.parse(await readFile(join(dataDir, folder, entry.name), 'utf8'))
      for (const item of [json].flat()) {
        if (typeof item.dataId !== 'number') {
          console.warn(`skipped (no numeric dataId): ${folder}/${entry.name} ${item.name ?? ''}`)
          continue
        }
        if (typeof item.name !== 'string' || item.name === '') {
          throw new Error(`${folder}/${entry.name}: dataId ${item.dataId} has no name`)
        }
        if (names.has(item.dataId) && names.get(item.dataId) !== item.name) {
          throw new Error(
            `dataId ${item.dataId} is both "${names.get(item.dataId)}" and "${item.name}"`,
          )
        }
        names.set(item.dataId, item.name)
      }
    }
  }
  return new Map([...names].sort(([a], [b]) => a - b))
}

const groupEntries = []
let total = 0
for (const [group, folders] of Object.entries(GROUPS)) {
  const names = await readGroup(folders)
  if (names.size === 0) throw new Error(`group ${group} is empty; did the package layout change?`)
  total += names.size
  const lines = [...names].map(([id, name]) => `    ${id}: ${JSON.stringify(name)},`)
  groupEntries.push(`  ${JSON.stringify(group)}: {\n${lines.join('\n')}\n  },`)
}

const today = new Date().toISOString().slice(0, 10)
const source = `// Generated by scripts/generate-upgrade-names.mjs. Do not edit by hand — run npm run generate:names.
// Source: ${PACKAGE}@${version} (MIT) — https://github.com/chiefpansancolt/clash-of-clans-data
// Generated: ${today}

export type NameGroup = ${Object.keys(GROUPS)
  .map((g) => JSON.stringify(g))
  .join(' | ')}

/** Upgrade names by group, keyed by the game's numeric data ID. */
export const UPGRADE_NAMES: Readonly<Record<NameGroup, Readonly<Record<number, string>>>> = {
${groupEntries.join('\n')}
}
`

const options = (await prettier.resolveConfig(outFile)) ?? {}
await writeFile(outFile, await prettier.format(source, { ...options, filepath: outFile }))
console.log(`Wrote ${total} names in ${groupEntries.length} groups to ${outFile}`)
